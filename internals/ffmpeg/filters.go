package ffmpeg

import (
	"fmt"
	"image"
	_ "image/jpeg" // logo dimensions
	_ "image/png"
	"os"
	"strings"
	"unicode"
)

func needsLogo(overlay string) bool { return overlay == OverlayLogo || overlay == OverlayBoth }
func needsText(overlay string) bool { return overlay == OverlayText || overlay == OverlayBoth }

// look is a request's watermark appearance: the configured defaults with the
// request's Style laid over them.
type look struct {
	logoPath  string
	position  string
	opacity   int // 0..100
	logoWidth int // px; -1 = native
	fontSize  int // px
	margin    int // px
	branded   bool
	logoH     int // rendered logo height in px, when known (0 = unknown)
}

func (e *Engine) look(st Style) look {
	l := look{
		logoPath:  e.cfg.LogoPath,
		position:  e.cfg.Position,
		opacity:   e.cfg.OpacityPct,
		logoWidth: e.cfg.LogoWidthPx,
		fontSize:  e.cfg.FontSizePx,
		margin:    e.cfg.MarginPx,
	}
	if st.LogoPath != "" {
		l.logoPath = st.LogoPath
	}
	if ValidPosition(st.Position) {
		l.position = st.Position
	}
	if st.OpacityPct > 0 {
		l.opacity = clamp(st.OpacityPct, 1, 100)
		l.branded = true
	}
	if st.FrameWidth > 0 {
		if st.LogoScalePct > 0 {
			l.logoWidth = max(16, st.FrameWidth*clamp(st.LogoScalePct, 1, 90)/100)
		}
		// Text and margins follow the picture size, never below the
		// configured minimums.
		l.fontSize = max(l.fontSize, st.FrameWidth*22/1000)
		l.margin = max(l.margin, st.FrameWidth*2/100)
	}
	if st.FontPx > 0 {
		l.fontSize = st.FontPx // fitted to the text by Watermark
	}
	if l.logoWidth <= 0 {
		l.logoWidth = -1 // keep native width
	}
	if w, h := imageSize(l.logoPath); w > 0 {
		if l.logoWidth > 0 {
			l.logoH = l.logoWidth * h / w
		} else {
			l.logoH = h
		}
	}
	return l
}

// imageSize reads a picture's dimensions from its header (0, 0 if unknown).
func imageSize(path string) (int, int) {
	f, err := os.Open(path)
	if err != nil {
		return 0, 0
	}
	defer f.Close()
	cfg, _, err := image.DecodeConfig(f)
	if err != nil {
		return 0, 0
	}
	return cfg.Width, cfg.Height
}

// Tiling grid: the logo on a 3x3 grid, the text on the 2x2 points between.
const tileCols, tileRows = 3, 3

// visualFilter builds the -filter_complex graph for a video/image watermark
// and returns it together with the label of the final video pad ("[vout]").
// The source video is [0:v]; the logo, when present, is always input [1:v].
//
// textFile is the path of a file holding the watermark text. The text itself
// never enters the filtergraph: drawtext reads it from textfile= with
// expansion disabled, so nothing an operator types can change the graph's
// structure or trigger drawtext's %{...} expansion. The path is generated by
// Watermark (os.CreateTemp), never taken from user input.
func (e *Engine) visualFilter(overlay, textFile string, l look) (graph, outLabel string) {
	logo, text := needsLogo(overlay), needsText(overlay)
	if !logo && !text {
		logo = true
	}
	var parts []string
	cur := "[0:v]"
	if logo {
		if l.position == "tiled" {
			n := tileCols * tileRows
			labels := make([]string, n)
			for i := range labels {
				labels[i] = fmt.Sprintf("[wm%d]", i)
			}
			parts = append(parts, e.logoChain(l, "[wmall]"), "[wmall]split="+itoa(n)+strings.Join(labels, ""))
			for i := 0; i < n; i++ {
				next := fmt.Sprintf("[t%d]", i)
				col, row := i%tileCols, i/tileCols
				xy := fmt.Sprintf("W*%d/%d-w/2:H*%d/%d-h/2", 2*col+1, 2*tileCols, 2*row+1, 2*tileRows)
				parts = append(parts, cur+labels[i]+"overlay="+xy+next)
				cur = next
			}
		} else {
			parts = append(parts, e.logoChain(l, "[wm]"), cur+"[wm]overlay="+overlayXY(l.position, l.margin)+"[tmp]")
			cur = "[tmp]"
		}
	}
	if text {
		if !logo {
			l.logoH = 0 // nothing to make room for
		}
		parts = append(parts, cur+e.drawtexts(textFile, l)+"[vout]")
	} else {
		// Rename the last pad: the caller maps [vout].
		parts[len(parts)-1] = strings.TrimSuffix(parts[len(parts)-1], cur) + "[vout]"
	}
	return strings.Join(parts, ";"), "[vout]"
}

// logoChain scales the logo, gives it an alpha channel and applies the
// opacity, leaving it on pad out.
func (e *Engine) logoChain(l look, out string) string {
	return fmt.Sprintf("[1:v]scale=%d:-1,format=rgba,colorchannelmixer=aa=%.2f%s",
		l.logoWidth, float64(clamp(l.opacity, 0, 100))/100, out)
}

// drawtexts renders the text once at the configured position, or on the
// points between the logo grid when tiled.
func (e *Engine) drawtexts(textFile string, l look) string {
	if l.position != "tiled" {
		return e.drawtext(textFile, l, drawtextXY(l.position, l.margin, l.logoH))
	}
	var chain []string
	for row := 1; row < tileRows; row++ {
		for col := 1; col < tileCols; col++ {
			xy := fmt.Sprintf("x=w*%d/%d-text_w/2:y=h*%d/%d-text_h/2", col, tileCols, row, tileRows)
			chain = append(chain, e.drawtext(textFile, l, xy))
		}
	}
	return strings.Join(chain, ",")
}

// drawtext renders one drawtext filter at xy, reading its text from textFile
// (see visualFilter). With a brand opacity the text fades with the logo;
// otherwise it keeps the historical fixed look.
func (e *Engine) drawtext(textFile string, l look, xy string) string {
	textA, boxA := 0.9, 0.35
	if l.branded {
		textA = min(0.95, float64(l.opacity)/100+0.3)
		boxA = textA * 0.4
	}
	return fmt.Sprintf(
		"drawtext=fontfile='%s':textfile='%s':expansion=none:fontcolor=white@%.2f:fontsize=%d:"+
			"box=1:boxcolor=black@%.2f:boxborderw=8:%s",
		escapeFilterPath(e.cfg.FontPath),
		escapeFilterPath(textFile),
		textA,
		l.fontSize,
		boxA,
		xy,
	)
}

// overlayXY maps a position name + margin to an ffmpeg overlay x:y expression
// (W/H are the base frame, w/h the overlay). "tiled" is handled by
// visualFilter itself.
func overlayXY(pos string, margin int) string {
	m := itoa(margin)
	switch pos {
	case "top-left":
		return m + ":" + m
	case "top-right":
		return "W-w-" + m + ":" + m
	case "bottom-left":
		return m + ":H-h-" + m
	case "center":
		return "(W-w)/2:(H-h)/2"
	default: // bottom-right
		return "W-w-" + m + ":H-h-" + m
	}
}

// drawtextXY maps a position name + margin to drawtext x=/y= expressions
// (w/h are the frame, text_w/text_h the rendered text box). logoH > 0 means
// a logo of that height sits at the same position: the text moves clear of
// it - above it at the bottom, below it at the top and in the centre.
func drawtextXY(pos string, margin, logoH int) string {
	m := itoa(margin)
	off := ""
	if logoH > 0 {
		off = "-" + itoa(logoH+margin/2)
	}
	below := ""
	if logoH > 0 {
		below = "+" + itoa(logoH+margin/2)
	}
	switch pos {
	case "top-left":
		return "x=" + m + ":y=" + m + below
	case "top-right":
		return "x=w-text_w-" + m + ":y=" + m + below
	case "bottom-left":
		return "x=" + m + ":y=h-text_h-" + m + off
	case "center":
		if logoH > 0 {
			return "x=(w-text_w)/2:y=h/2+" + itoa(logoH/2+margin/2)
		}
		return "x=(w-text_w)/2:y=(h-text_h)/2"
	default: // bottom-right
		return "x=w-text_w-" + m + ":y=h-text_h-" + m + off
	}
}

// SanitizeText makes operator-supplied watermark text safe to render: control
// characters (newlines included) become spaces, surrounding space is trimmed,
// and the result is capped at MaxTextRunes. It is a content rule, not an
// escaping step - the text reaches ffmpeg through a file, never the graph.
func SanitizeText(s string) string {
	out := make([]rune, 0, len(s))
	for _, r := range s {
		if unicode.IsControl(r) {
			r = ' '
		}
		out = append(out, r)
		if len(out) >= MaxTextRunes {
			break
		}
	}
	return strings.TrimSpace(string(out))
}

// MaxTextRunes bounds the watermark text burned into a preview.
const MaxTextRunes = 200

// escapeFilterPath normalises a server-side file path for a single-quoted
// filtergraph value: forward slashes, and the Windows drive colon escaped so
// ffmpeg does not read it as an option separator. Paths are config values or
// os.CreateTemp results, never user input; Watermark refuses one containing a
// single quote, which no quoting level could carry.
func escapeFilterPath(p string) string {
	p = strings.ReplaceAll(p, `\`, `/`)
	p = strings.ReplaceAll(p, `:`, `\:`)
	return p
}

func clamp(v, lo, hi int) int {
	if v < lo {
		return lo
	}
	if v > hi {
		return hi
	}
	return v
}
